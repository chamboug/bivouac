import type { ValidationError } from "./instance.js";
import type { AppManifest, PlatformConfig, SiteManifest } from "./schema.js";

/**
 * Names of the platform's containers on the shared Docker network. Caddy
 * reaches every upstream by container name, through Docker's internal DNS:
 * no container port is ever published, except Caddy's.
 */
export const PLATFORM_CONTAINERS = {
  caddy: "bivouac-caddy",
  postgres: "bivouac-postgres",
  pocketId: "bivouac-pocket-id",
} as const;

/** Pocket ID's listening port (verified, Pocket ID docs: `PORT`, default 1411). */
export const POCKET_ID_PORT = 1411;

/** Subdomain of Pocket ID. Final: it shows in users' passkey dialogs (D40). */
export const AUTH_SUBDOMAIN = "auth";

export function appContainerName(app: string): string {
  return `bivouac-app-${app}`;
}

/**
 * Pocket ID's first-admin page and its API. They create an admin account for
 * whoever gets there first (verified), so Caddy refuses them, except from the
 * owner's IP while the instance is being installed (D15).
 */
const SETUP_PATHS = ["/setup", "/setup/*", "/api/signup/setup", "/api/signup/setup/*"];

export interface CaddyfileResult {
  caddyfile: string;
  errors: ValidationError[];
}

/**
 * Generates the whole Caddyfile from the instance repo. Caddy gets HTTPS
 * certificates on its own, one per host (no wildcard certificate, no DNS
 * plugin). The output is in `caddy fmt` style, so `caddy validate` prints no
 * formatting warning.
 */
export function generateCaddyfile(
  platform: PlatformConfig,
  apps: AppManifest[],
  sites: SiteManifest[],
): CaddyfileResult {
  const errors: ValidationError[] = [];
  const blocks: string[] = [
    block("", [
      "# Generated by the Bivouac reconciler from the instance repo: do not edit.",
      "# The admin API only listens inside Caddy's container; the reconciler",
      "# reloads the config with `docker exec`.",
      "admin localhost:2019",
    ]),
    authBlock(platform),
  ];

  for (const app of apps) {
    const file = `apps/${app.name}.yml`;
    if (app.auth === "forward") {
      errors.push({ file, message: "auth 'forward' is not available yet (it comes with Tinyauth, D44)" });
      continue;
    }
    // oidc, local and public look the same to Caddy: the app handles login.
    const hosts = [`${app.name}.${platform.domain}`, ...app.domains];
    blocks.push(block(hosts.join(", "), [`reverse_proxy ${appContainerName(app.name)}:${app.port}`]));
  }

  for (const site of sites) {
    errors.push({ file: `sites/${site.name}.yml`, message: "static sites are not available yet (layer 6 of the build order)" });
  }

  return { caddyfile: `${blocks.join("\n\n")}\n`, errors };
}

function authBlock(platform: PlatformConfig): string {
  const upstream = `${PLATFORM_CONTAINERS.pocketId}:${POCKET_ID_PORT}`;
  const setupFrom = platform.auth?.setupFrom;
  const matcher = setupFrom
    ? [
        "@setup {",
        `\tpath ${SETUP_PATHS.join(" ")}`,
        `\tnot remote_ip ${setupFrom}`,
        "}",
      ]
    : [`@setup path ${SETUP_PATHS.join(" ")}`];
  return block(`${AUTH_SUBDOMAIN}.${platform.domain}`, [
    ...matcher,
    "respond @setup 403",
    `reverse_proxy ${upstream}`,
  ]);
}

function block(address: string, lines: string[]): string {
  const body = lines.map((line) => `\t${line}`).join("\n");
  return address ? `${address} {\n${body}\n}` : `{\n${body}\n}`;
}
